#!/usr/bin/env bash
#
# sync-design-language.sh
#
# The chapter design language lives in exactly one place:
#
#     parts/02-benchmarking/_archive/v1-m2lab/_shared/m2lab-deck.css
#     parts/02-benchmarking/_archive/v1-m2lab/_shared/m2lab-deck.js
#
# but every episode deck has to be a single self-contained file. On recording
# day the deck gets opened straight from disk, dragged between machines and
# thrown into fullscreen; a broken relative path at that moment costs a shoot.
#
# So this script inlines the shared files into each episode deck, between the
# marker comments below. Edit the shared files, run this, and all nine decks
# pick up the change while staying standalone.
#
#     ./scripts/sync-design-language.sh
#
# The markers must already exist in each deck:
#     /* @shared:css:start */ ... /* @shared:css:end */
#     /* @shared:js:start */  ... /* @shared:js:end */
#
# Everything between a pair is replaced. Everything outside is left alone —
# that is where each episode's own choreography and content live.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHARED="$ROOT/parts/02-benchmarking/_archive/v1-m2lab/_shared"
CSS="$SHARED/m2lab-deck.css"
JS="$SHARED/m2lab-deck.js"

for f in "$CSS" "$JS"; do
  [[ -f "$f" ]] || { echo "missing shared source: $f" >&2; exit 1; }
done

shopt -s nullglob
decks=("$ROOT"/parts/02-benchmarking/_archive/v1-m2lab/*/M2Lab_Episode_*_Design_Mockup.html)
(( ${#decks[@]} )) || { echo "no episode decks found under $ROOT/parts/02-benchmarking/_archive/v1-m2lab" >&2; exit 1; }

synced=0
skipped=0

for deck in "${decks[@]}"; do
  rel="${deck#"$ROOT"/}"

  if ! grep -q '@shared:css:start' "$deck" || ! grep -q '@shared:js:start' "$deck"; then
    echo "  skip  $rel  (no @shared markers)"
    skipped=$((skipped + 1))
    continue
  fi

  CSS_FILE="$CSS" JS_FILE="$JS" python3 - "$deck" <<'PY'
import os, re, sys

deck = sys.argv[1]
with open(deck, encoding='utf-8') as fh:
    html = fh.read()

def inline(text, kind, payload):
    start = f'/* @shared:{kind}:start */'
    end   = f'/* @shared:{kind}:end */'
    pattern = re.compile(
        re.escape(start) + '.*?' + re.escape(end),
        re.DOTALL)
    banner = (f'{start}\n'
              f'/* Generated by scripts/sync-design-language.sh — do not edit here.\n'
              f'   Source: parts/02-benchmarking/_archive/v1-m2lab/_shared/m2lab-deck.{kind}  */\n'
              f'{payload.rstrip()}\n'
              f'{end}')
    out, n = pattern.subn(lambda _: banner, text, count=1)
    if n != 1:
        raise SystemExit(f'{deck}: expected one {kind} marker pair, found {n}')
    return out

for kind, env in (('css', 'CSS_FILE'), ('js', 'JS_FILE')):
    with open(os.environ[env], encoding='utf-8') as fh:
        html = inline(html, kind, fh.read())

with open(deck, 'w', encoding='utf-8') as fh:
    fh.write(html)
PY

  echo "  sync  $rel"
  synced=$((synced + 1))
done

echo
echo "synced $synced deck(s), skipped $skipped"
